def glyph_from_bitmap(rows):
    pen = TTGlyphPen(None)
    for r, row in enumerate(rows):
        y0 = (6 - r) * PX
        for c, ch in enumerate(row):
            if ch != '#':
                continue
            x0 = c * PX
            pen.moveTo((x0, y0))
            pen.lineTo((x0, y0 + PX))
            pen.lineTo((x0 + PX, y0 + PX))
            pen.lineTo((x0 + PX, y0))
            pen.closePath()
    return pen.glyph()


def main():
    names = ['.notdef', 'space']
    cmap = {32: 'space'}
    glyphs = {'.notdef': glyph_from_bitmap(["#####", "#...#", "#...#", "#...#", "#...#", "#...#", "#####"]),
              'space': TTGlyphPen(None).glyph()}
    for ch, rows in GLYPHS.items():
        name = 'uni%04X' % ord(ch)
        names.append(name)
        glyphs[name] = glyph_from_bitmap(rows)
        cmap[ord(ch)] = name
        if ch.isalpha() and ch.isupper():
            cmap[ord(ch.lower())] = name  # all-caps font
    fb = FontBuilder(8 * PX, isTTF=True)
    fb.setupGlyphOrder(names)
    fb.setupCharacterMap(cmap)
    fb.setupGlyf(glyphs)
    fb.setupHorizontalMetrics({n: (6 * PX, 0) for n in names})
    fb.setupHorizontalHeader(ascent=7 * PX, descent=-1 * PX)
    fb.setupNameTable({'familyName': 'StickPix', 'styleName': 'Regular'})
    fb.setupOS2(sTypoAscender=7 * PX, sTypoDescender=-1 * PX, usWinAscent=7 * PX, usWinDescent=1 * PX)
    fb.setupPost()
    out = os.path.join(os.path.dirname(__file__), '..', 'assets', 'stickpix.ttf')
    fb.save(out)
    print('wrote', os.path.normpath(out), len(names), 'glyphs')


if __name__ == '__main__':
    main()
